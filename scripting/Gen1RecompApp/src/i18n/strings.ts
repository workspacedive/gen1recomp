const useGerman = Device.systemLanguageCode.toLowerCase().startsWith("de")

export function t(key: TextKey): string {
  return useGerman ? de[key] : en[key]
}

export function formatDate(value: string): string {
  const date = new Date(value)
  if (!Number.isFinite(date.getTime())) return t("notAvailable")
  return new Intl.DateTimeFormat(useGerman ? "de-DE" : "en-US", {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(date)
}
